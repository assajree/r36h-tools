static void draw_char(SDL_Renderer *rend, int x, int y, char c, int scale) {
    if (c < 32 || c > 126) c = ' ';
    const unsigned char *glyph = font8x8_basic[c - 32];
    for (int row = 0; row < 8; row++) {
        unsigned char bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            if (bits & (1 << col)) {
                SDL_Rect r = { x + col * scale, y + row * scale, scale, scale };
                SDL_RenderFillRect(rend, &r);
            }
        }
    }
}

static void draw_text(SDL_Renderer *rend, int x, int y, const char *str, int scale, Uint8 r, Uint8 g, Uint8 b) {
    SDL_SetRenderDrawColor(rend, r, g, b, 255);
    int cur_x = x;
    while (*str) {
        draw_char(rend, cur_x, y, *str, scale);
        cur_x += 8 * scale;
        str++;
    }
}

static int text_width(const char *str, int scale) {
    return (int)strlen(str) * 8 * scale;
}

static void draw_centered_text(SDL_Renderer *rend, int center_x, int y, const char *str, int scale, Uint8 r, Uint8 g, Uint8 b) {
    int w = text_width(str, scale);
    draw_text(rend, center_x - (w / 2), y, str, scale, r, g, b);
}

int main(int argc, char *argv[]) {
    int total_seconds = 3;
    if (argc > 1) {
        int s = atoi(argv[1]);
        if (s > 0 && s <= 10) total_seconds = s;
    }

    /* Initialize SDL2 Video and Joystick */
    if (SDL_Init(SDL_INIT_VIDEO | SDL_INIT_JOYSTICK) < 0) {
        fprintf(stderr, "SDL_Init error: %s\n", SDL_GetError());
        return 0; /* Fallback to proceed if display fails */
    }

    /* Open first joystick if available to capture gamepad input */
    SDL_Joystick *joy = NULL;
    if (SDL_NumJoysticks() > 0) {
        joy = SDL_JoystickOpen(0);
    }

    /* Trigger short haptic vibration */
    system("/usr/local/bin/sdl_rumble 3 200 >/dev/null 2>&1 &");

    SDL_Window *win = SDL_CreateWindow("Shutdown Overlay",
                                       SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED,
                                       SCREEN_W, SCREEN_H,
                                       SDL_WINDOW_SHOWN | SDL_WINDOW_FULLSCREEN);
    if (!win) {
        fprintf(stderr, "CreateWindow error: %s\n", SDL_GetError());
        if (joy) SDL_JoystickClose(joy);
        SDL_Quit();
        return 0;
    }

    SDL_Renderer *rend = SDL_CreateRenderer(win, -1, SDL_RENDERER_ACCELERATED | SDL_RENDERER_PRESENTVSYNC);
    if (!rend) {
        rend = SDL_CreateRenderer(win, -1, SDL_RENDERER_SOFTWARE);
    }

    Uint32 start_time = SDL_GetTicks();
    Uint32 duration_ms = total_seconds * 1000;
    int cancelled = 0;

    SDL_Event ev;

    /* Main countdown render loop */
    while (1) {
        Uint32 now = SDL_GetTicks();
        Uint32 elapsed = now - start_time;

        /* Check inputs for cancellation */
        while (SDL_PollEvent(&ev)) {
            if (ev.type == SDL_KEYDOWN) {
                cancelled = 1;
                break;
            } else if (ev.type == SDL_JOYBUTTONDOWN) {
                cancelled = 1;
                break;
            } else if (ev.type == SDL_JOYHATMOTION) {
                if (ev.jhat.value != SDL_HAT_CENTERED) {
                    cancelled = 1;
                    break;
                }
            } else if (ev.type == SDL_QUIT) {
                cancelled = 1;
                break;
            }
        }

        if (cancelled) {
            break;
        }

        if (elapsed >= duration_ms) {
            break; /* Timer finished -> Proceed to shutdown */
        }

        /* 1. Backdrop Overlay */
        SDL_SetRenderDrawColor(rend, 10, 10, 14, 255);
        SDL_RenderClear(rend);

        /* 2. Modal Card (shadcn/ui dark zinc container) */
        int card_x = 70;
        int card_y = 70;
        int card_w = 500;
        int card_h = 340;

        /* Card background (#18181b) */
        SDL_Rect card_rect = { card_x, card_y, card_w, card_h };
        SDL_SetRenderDrawColor(rend, 24, 24, 27, 255);
        SDL_RenderFillRect(rend, &card_rect);

        /* Card Outer Accent Glow & Border (#f59e0b amber & #3f3f46) */
        SDL_SetRenderDrawColor(rend, 245, 158, 11, 255);
        SDL_RenderDrawRect(rend, &card_rect);
        SDL_Rect border_inner = { card_x + 1, card_y + 1, card_w - 2, card_h - 2 };
        SDL_SetRenderDrawColor(rend, 63, 63, 70, 255);
        SDL_RenderDrawRect(rend, &border_inner);

        /* 3. Top Header Badge Pill */
        int badge_w = 200;
        int badge_h = 32;
        int badge_x = 320 - (badge_w / 2);
        int badge_y = card_y + 24;
        SDL_Rect badge_rect = { badge_x, badge_y, badge_w, badge_h };
        SDL_SetRenderDrawColor(rend, 69, 26, 3, 255); /* Deep amber background */
        SDL_RenderFillRect(rend, &badge_rect);
        SDL_SetRenderDrawColor(rend, 217, 119, 6, 255); /* Amber border */
        SDL_RenderDrawRect(rend, &badge_rect);

        draw_centered_text(rend, 320, badge_y + 8, "POWER OFF", 2, 251, 191, 36);

        /* 4. Large Countdown Digit Display */
        int remaining_s = (int)((duration_ms - elapsed + 999) / 1000);
        if (remaining_s < 1) remaining_s = 1;
        char num_str[4];
        snprintf(num_str, sizeof(num_str), "%d", remaining_s);

        /* Massive 8x scale digit (64x64 px) */
        Uint8 cr = 245, cg = 158, cb = 11;
        if (remaining_s == 1) {
            cr = 244; cg = 63; cb = 94; /* Red pulse on 1 */
        }
        draw_centered_text(rend, 320, card_y + 80, num_str, 8, cr, cg, cb);

        /* Subtitle */
        draw_centered_text(rend, 320, card_y + 160, "SHUTTING DOWN IN SECONDS", 1, 161, 161, 170);

        /* 5. Smooth Progress Bar */
        int bar_w = 380;
        int bar_h = 14;
        int bar_x = 320 - (bar_w / 2);
        int bar_y = card_y + 195;

        SDL_Rect bar_bg = { bar_x, bar_y, bar_w, bar_h };
        SDL_SetRenderDrawColor(rend, 39, 39, 42, 255);
        SDL_RenderFillRect(rend, &bar_bg);

        float pct = 1.0f - ((float)elapsed / (float)duration_ms);
        if (pct < 0.0f) pct = 0.0f;
        int fill_w = (int)(bar_w * pct);
        if (fill_w > 0) {
            SDL_Rect bar_fill = { bar_x, bar_y, fill_w, bar_h };
            SDL_SetRenderDrawColor(rend, cr, cg, cb, 255);
            SDL_RenderFillRect(rend, &bar_fill);
        }

        /* 6. Action Legend Pill */
        int action_w = 380;
        int action_h = 36;
        int action_x = 320 - (action_w / 2);
        int action_y = card_y + 245;

        SDL_Rect action_rect = { action_x, action_y, action_w, action_h };
        SDL_SetRenderDrawColor(rend, 39, 39, 42, 255);
        SDL_RenderFillRect(rend, &action_rect);
        SDL_SetRenderDrawColor(rend, 63, 63, 70, 255);
        SDL_RenderDrawRect(rend, &action_rect);

        draw_centered_text(rend, 320, action_y + 10, "PRESS ANY BUTTON TO CANCEL", 2, 250, 250, 250);

        SDL_RenderPresent(rend);
        SDL_Delay(16); /* ~60 FPS smooth animation */
    }

    /* Post-loop feedback animation */
    if (cancelled) {
        /* Vibration confirmation of cancel */
        system("/usr/local/bin/sdl_rumble 2 100 >/dev/null 2>&1 &");

        SDL_SetRenderDrawColor(rend, 10, 10, 14, 255);
        SDL_RenderClear(rend);

        SDL_Rect card_rect = { 70, 70, 500, 340 };
        SDL_SetRenderDrawColor(rend, 24, 24, 27, 255);
        SDL_RenderFillRect(rend, &card_rect);

        /* Green success border (#22c55e) */
        SDL_SetRenderDrawColor(rend, 34, 197, 94, 255);
        SDL_RenderDrawRect(rend, &card_rect);

        /* Green Badge */
        SDL_Rect badge_rect = { 320 - 100, 70 + 24, 200, 32 };
        SDL_SetRenderDrawColor(rend, 20, 83, 45, 255);
        SDL_RenderFillRect(rend, &badge_rect);
        SDL_SetRenderDrawColor(rend, 34, 197, 94, 255);
        SDL_RenderDrawRect(rend, &badge_rect);
        draw_centered_text(rend, 320, 70 + 32, "CANCELLED", 2, 74, 222, 128);

        draw_centered_text(rend, 320, 70 + 110, "SHUTDOWN CANCELLED", 3, 250, 250, 250);
        draw_centered_text(rend, 320, 70 + 190, "Returning to game...", 2, 161, 161, 170);

        SDL_RenderPresent(rend);
        SDL_Delay(600); /* Show for 0.6s then clean exit */
    } else {
        /* Shutting down notice */
        SDL_SetRenderDrawColor(rend, 10, 10, 14, 255);
        SDL_RenderClear(rend);

        SDL_Rect card_rect = { 70, 70, 500, 340 };
        SDL_SetRenderDrawColor(rend, 24, 24, 27, 255);
        SDL_RenderFillRect(rend, &card_rect);

        SDL_SetRenderDrawColor(rend, 239, 68, 68, 255);
        SDL_RenderDrawRect(rend, &card_rect);

        draw_centered_text(rend, 320, 70 + 110, "SHUTTING DOWN...", 3, 250, 250, 250);
        draw_centered_text(rend, 320, 70 + 190, "Saving game and data...", 2, 161, 161, 170);

        SDL_RenderPresent(rend);
        SDL_Delay(300);
    }

    if (joy) SDL_JoystickClose(joy);
    SDL_DestroyRenderer(rend);
    SDL_DestroyWindow(win);
    SDL_Quit();

    return cancelled ? 1 : 0;
}
